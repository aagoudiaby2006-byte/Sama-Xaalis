export const dictionaries: Record<Language, Record<TranslationKey, string>> = { fr, en };

export type TParams = Record<string, string | number>;

export function translate(lang: Language, key: TranslationKey, params?: TParams): string {
  let s = dictionaries[lang][key] ?? dictionaries.fr[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** The app is in French by default, whatever the device language; English is chosen in Profile. */
export const DEFAULT_LANGUAGE: Language = 'fr';

type I18nValue = { lang: Language; t: (key: TranslationKey, params?: TParams) => string };
const I18nContext = createContext<I18nValue>({ lang: 'fr', t: (k, p) => translate('fr', k, p) });

export function I18nProvider({ lang, children }: { lang: Language; children: ReactNode }) {
  const t = useCallback((key: TranslationKey, params?: TParams) => translate(lang, key, params), [lang]);
  const value = useMemo(() => ({ lang, t }), [lang, t]);
  return createElement(I18nContext.Provider, { value }, children);
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}

/** Localized date, independent of Intl support: "27/09/2026" (fr) or "09/27/2026" (en). */
export function formatDate(iso: string, lang: Language): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '—';
  const dd = String(d.getDate()).padStart(2, '0');
  const mm = String(d.getMonth() + 1).padStart(2, '0');
  return lang === 'fr' ? `${dd}/${mm}/${d.getFullYear()}` : `${mm}/${dd}/${d.getFullYear()}`;
}
